async function checkInterface(page, out) {
  const fs = require('node:fs/promises');
  const path = require('node:path');
  const checks = [];
  const check = (name, ok) => { if (!ok) throw new Error(name); checks.push(name); };
  const km = page.getByRole('textbox', {name:'乘车里程（公里）',exact:true});
  const shot = name => page.screenshot({path:path.join(out, 'screenshots', name), fullPage:false});
  const getRows = () => page.locator('#fare-rows tr').evaluateAll(rows => rows.map(r => [...r.cells].slice(0,3).map(c=>c.textContent.trim())));
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  check('首次打开里程为空且未选城市', await km.inputValue() === '' && await page.locator('#city-list input:checked').count() === 0);
  check('缺省显示教程、不显示错误和票价', await page.locator('#query-tutorial').isVisible() && await page.locator('#distance-error').isHidden() && await page.locator('#fare-table').isHidden());
  check('城市45个且天津排在最后', await page.locator('#city-list label').count() === 45 && (await page.locator('#city-list label').last().innerText()) === '天津（站数计价）');
  check('删除里程计价筛选开关', await page.locator('#distance-only').count() === 0);
  check('移除装饰英文及宣传文字', !/FARE COMPARISON|DATA & REFERENCES|METRO FARE|一目了然|温馨提示/.test(await page.locator('body').innerText()));
  check('无统计卡片和提示横幅', await page.locator('.summary,.scope-notice,#toast,.intro,.badge').count() === 0);
  await shot('01-start.png');
  await km.fill('16');
  check('仅填写里程仍显示教程', await page.locator('#query-tutorial').isVisible() && await page.locator('#export-csv').isDisabled());
  await km.fill('');
  await page.getByRole('radio',{name:'单城查询',exact:true}).check();
  await page.getByRole('radio',{name:'上海',exact:true}).check();
  check('仅选择城市仍显示教程', await page.locator('#query-tutorial').isVisible() && await page.locator('#rule-detail').isHidden());
  await km.fill('16');
  check('上海16公里4元', (await page.locator('#fare-rows .fare-number').innerText()) === '4' && await page.locator('#query-tutorial').isHidden());
  await shot('02-single.png');
  await km.fill('16.01');
  check('上海跨档5元', (await page.locator('#fare-rows .fare-number').innerText()) === '5');
  await km.fill('');
  check('清空里程返回教程并清掉旧结果', await page.locator('#query-tutorial').isVisible() && await page.locator('#fare-rows tr').count() === 0 && await page.locator('#distance-error').isHidden());
  for (const input of ['-1', '1e2', '0', '500.01', '1.234']) {
    await km.fill(input);
    check('拒绝非法输入:'+input, await page.locator('#distance-error').isVisible() && await page.locator('#export-csv').isDisabled() && await page.locator('#fare-table').isHidden());
  }
  await shot('03-invalid.png');
  await km.fill('76.01');
  await page.getByRole('radio',{name:'多城对比',exact:true}).check();
  await page.locator('#clear-selection').click();
  check('清空城市返回教程并清掉旧结果', await page.locator('#query-tutorial').isVisible() && await page.locator('#fare-rows tr').count() === 0 && await page.locator('#rule-detail').isHidden());
  for(const name of ['北京','南京','沈阳']) await page.getByRole('checkbox',{name,exact:true}).check();
  check('三城排序和价差', JSON.stringify(await getRows()) === JSON.stringify([['沈阳','7','0'],['北京','9','2'],['南京','11','4']]));
  await shot('04-compare.png');
  await page.locator('#fare-rows tr').filter({hasText:'南京'}).getByRole('button',{name:'规则',exact:true}).click();
  check('南京续程区间', (await page.locator('#rule-detail').innerText()).includes('76 < 里程 ≤ 91 公里'));
  await shot('05-rule.png');
  await page.getByRole('checkbox',{name:'天津（站数计价）',exact:true}).check();
  await page.locator('#fare-rows tr').filter({hasText:'天津'}).getByRole('button',{name:'规则',exact:true}).click();
  check('天津保留但不做公里换算', (await page.locator('#fare-rows tr').last().innerText()).includes('天津') && (await page.locator('#rule-detail').innerText()).includes('不支持里程换算'));
  await shot('06-stations.png');
  await page.getByRole('radio',{name:'单城查询',exact:true}).check();
  await page.getByRole('radio',{name:'天津（站数计价）',exact:true}).check();
  check('天津可以单独选择', (await getRows()).length === 1 && (await getRows())[0][1] === '不适用');
  await page.getByRole('radio',{name:'多城对比',exact:true}).check();
  await page.locator('#select-all').click();
  check('全选包含天津共45城', await page.locator('#city-list input:checked').count() === 45 && await page.locator('#fare-rows tr').count() === 45);
  await page.locator('#clear-selection').click();
  for(const name of ['北京','南京','沈阳']) await page.getByRole('checkbox',{name,exact:true}).check();
  await page.locator('#city-search').fill('南');
  check('城市搜索不移除已有选择', await page.locator('#fare-rows tr').count() === 3);
  await page.locator('#city-search').fill('');
  await page.locator('#sort').selectOption('name');
  check('按名称排序', JSON.stringify((await getRows()).map(r=>r[0])) === JSON.stringify(['北京','南京','沈阳']));
  await page.locator('#sort').selectOption('fare');
  await page.getByRole('button',{name:'数据来源',exact:true}).click();
  check('来源表无超链接', await page.locator('#source-rows a').count() === 0);
  await page.locator('#source-search').fill('checkedon');
  check('不搜索内部键名', await page.locator('#source-rows').innerText() === '无匹配记录');
  await page.locator('#source-search').fill('从发改委或地铁公司官网获取');
  check('可按来源文字搜索', await page.locator('#source-rows tr').count() === 45);
  await page.locator('#source-search').fill('南京');
  check('城市来源搜索', await page.locator('#source-rows tr').count() === 1);
  await shot('07-sources.png');
  await page.locator('#source-rows button').click();
  check('来源详情保留规则及生效且无链接', (await page.locator('#dialog-body').innerText()).includes('规则生效') && await page.locator('#dialog-body a').count() === 0);
  await shot('08-source-detail.png');
  await page.getByRole('button',{name:'关闭来源详情',exact:true}).click();
  await page.getByRole('button',{name:'票价查询',exact:true}).click();
  check('切换页面保留本次输入', await km.inputValue() === '76.01' && await page.locator('#fare-rows tr').count() === 3);
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#export-csv').click();
  const download = await downloadPromise;
  const exportPath = path.join(out, 'browser-export.csv');
  await download.saveAs(exportPath);
  check('导出文件名', download.suggestedFilename() === '里程票价对比-76.01公里.csv');
  const csv = await fs.readFile(exportPath, 'utf8');
  check('CSV含BOM及本次三城结果', csv.charCodeAt(0) === 0xfeff && ['沈阳','北京','南京'].every(name=>csv.includes(name)) && !csv.includes('天津'));
  await shot('09-export.png');
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>scrollTo(0,0));
  check('窄屏页面无横向溢出', await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth));
  await shot('10-mobile.png');
  await page.setViewportSize({width:1360,height:900});
  await page.context().setOffline(true);
  await km.fill('20');
  check('离线查询', (await getRows()).every(r=>r[1] === '5'));
  await page.context().setOffline(false);
  await page.reload();
  check('重新打开不恢复旧输入', await km.inputValue() === '' && await page.locator('#city-list input:checked').count() === 0 && await page.locator('#query-tutorial').isVisible());
  return {passed:checks.length,checks};
}
module.exports = checkInterface;
